import json
import logging
from functools import lru_cache

import joblib
import numpy as np
import pandas as pd
from fastapi import HTTPException

from app.config import MODEL_DIR
from app.ml.pipelines import FEATURES

logger = logging.getLogger(__name__)


class ModelService:
    def __init__(self, directory=MODEL_DIR):
        self.directory = directory
        self.pipeline = None
        self.metadata = None
        self.eda = None

    def load(self):
        if self.pipeline is not None:
            return
        try:
            pointer = json.loads((self.directory / "current.json").read_text(encoding="utf-8"))
            run = self.directory / pointer["version"]
            metadata = json.loads((run / "metrics.json").read_text(encoding="utf-8"))
            eda = json.loads((run / "eda.json").read_text(encoding="utf-8"))
            # Load only trusted local artifacts generated by scripts.train.
            pipeline = joblib.load(run / f"{pointer['model_name']}.joblib")
            self.metadata, self.eda, self.pipeline = metadata, eda, pipeline
        except FileNotFoundError as error:
            raise HTTPException(503, "Brak wytrenowanego modelu. Pobierz train.csv i uruchom python -m scripts.train w katalogu backend.") from error
        except Exception as error:
            logger.exception("Nie udało się wczytać artefaktów modelu")
            raise HTTPException(503, "Nie można wczytać modelu. Sprawdź artefakty i wersje bibliotek lub ponów trening.") from error

    def predict(self, features):
        self.load()
        frame = pd.DataFrame([{key: np.nan if value is None else value for key, value in features.items()}], columns=FEATURES)
        try:
            price = float(self.pipeline.predict(frame)[0])
            if not np.isfinite(price):
                raise ValueError("Nonfinite prediction")
        except Exception as error:
            logger.exception("Błąd predykcji")
            raise HTTPException(503, "Model nie może obliczyć prognozy. Sprawdź zgodność artefaktów.") from error
        return {"price_usd": round(max(0, price), 2), "currency": "USD", "model_name": self.metadata["selected_model"], "model_version": self.metadata["version"]}


@lru_cache
def get_model_service():
    return ModelService()
